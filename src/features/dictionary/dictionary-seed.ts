import { CEFR_LEVELS, type CefrIndex } from "./cefr.ts";
import { sqlString } from "./seed-sql.ts";
import type { FilledTranslations } from "./dictionary-translations.ts";
import { TOPICS } from "./topics.ts";

// The word lists' part-of-speech names → the ones words.part_of_speech uses.
const LIST_TO_WORD_POS: Record<string, string> = {
  noun: "noun",
  verb: "verb",
  adjective: "adj",
  adverb: "adv",
  conjunction: "conj",
  determiner: "det",
  interjection: "intj",
  number: "num",
  preposition: "prep",
  pronoun: "pron",
};

// Same rule as custom words (custom-word.ts LEMMA_PATTERN): plain lowercase
// English, so every entry can become a word.
const LEMMA = /^[a-z]+([ '-][a-z]+)*$/;

export type DictionaryEntry = {
  lemma: string;
  pos: string; // the easiest entry's part of speech
  partsOfSpeech: string[]; // every part of speech the lists give the word
  level: string;
  source: string;
  topics: string[];
  ru: string; // from content/dictionary/translations.csv; "" when not filled in
  ro: string;
  definitionRu: string; // same CSV; "" when not filled in
  definitionRo: string;
};

// One entry per headword: its easiest level (learners meet that meaning first).
// Topics are filled by hand in the seed file; `topics` keeps them across runs.
export function dictionaryEntries(
  index: CefrIndex,
  topics: Map<string, string[]> = new Map(),
  translations: FilledTranslations = new Map(),
): DictionaryEntry[] {
  const entries: DictionaryEntry[] = [];
  for (const [lemma, listed] of index) {
    if (!LEMMA.test(lemma) || lemma.length > 60) continue;
    const easiest = listed.reduce((best, e) =>
      CEFR_LEVELS.indexOf(e.level) < CEFR_LEVELS.indexOf(best.level) ? e : best,
    );
    const partsOfSpeech = [...new Set(listed.map((e) => LIST_TO_WORD_POS[e.pos]).filter(Boolean))].sort();
    entries.push({
      lemma,
      pos: LIST_TO_WORD_POS[easiest.pos] ?? "",
      partsOfSpeech,
      level: easiest.level,
      source: easiest.source,
      topics: topics.get(lemma) ?? [],
      ru: translations.get(lemma)?.ru ?? "",
      ro: translations.get(lemma)?.ro ?? "",
      definitionRu: translations.get(lemma)?.definitionRu ?? "",
      definitionRo: translations.get(lemma)?.definitionRo ?? "",
    });
  }
  return entries.sort((a, b) => a.lemma.localeCompare(b.lemma));
}

// Topics already written in a seed file, by lemma: the last value of each
// row, e.g. ('goal', 'noun', 'A2', 'cefr-j', '{noun}', null, null, '{sport,work}').
// (Older files had fewer values before the topics; all shapes are read.)
export function topicsFromSeed(sql: string): Map<string, string[]> {
  const topics = new Map<string, string[]>();
  const row = /^\s*\('((?:[^']|'')*)',.*'\{([^}]*)\}'\),?$/gm;
  for (const [, lemma, list] of sql.matchAll(row)) {
    const values = list
      .split(",")
      .map((t) => t.trim())
      .filter(Boolean);
    if (values.length > 0) topics.set(lemma.replace(/''/g, "'"), values);
  }
  return topics;
}

// Idempotent SQL for public.dictionary_entries, in chunks the SQL editor handles well.
export function buildDictionarySeedSql(entries: DictionaryEntry[], chunkSize = 1000): string {
  const parts = [
    "-- Dictionary pool: generated by scripts/word-sets.ts (npm run words:dictionary).",
    "-- Levels from the CEFR-J Wordlist (Tono Laboratory, TUFS) and Octanove C1/C2 (CC BY-SA 4.0).",
    "-- Row: (lemma, main part of speech, CEFR level, level source, all parts of speech, RU, RO, RU definition, RO definition, topics).",
    "-- Edit only the last value, the topics, e.g. '{sport,health}'. Translations come from",
    "-- content/dictionary/translations.csv (fill them in there, then run the command again);",
    `-- allowed topics: ${TOPICS.join(", ")}. Re-running the command keeps them.`,
    "begin;",
  ];
  for (let i = 0; i < entries.length; i += chunkSize) {
    const rows = entries
      .slice(i, i + chunkSize)
      .map(
        (e) =>
          `  (${[
            e.lemma,
            e.pos,
            e.level,
            e.source,
            `{${e.partsOfSpeech.join(",")}}`,
            e.ru || null,
            e.ro || null,
            e.definitionRu || null,
            e.definitionRo || null,
            `{${e.topics.join(",")}}`,
          ]
            .map(sqlString)
            .join(", ")})`,
      );
    parts.push(
      "insert into public.dictionary_entries (lemma, part_of_speech, cefr_level, level_source, parts_of_speech, translation_ru, translation_ro, definition_ru, definition_ro, topics)",
      `values\n${rows.join(",\n")}`,
      "on conflict (lemma) do update set part_of_speech = excluded.part_of_speech, cefr_level = excluded.cefr_level, level_source = excluded.level_source, parts_of_speech = excluded.parts_of_speech, translation_ru = excluded.translation_ru, translation_ro = excluded.translation_ro, definition_ru = excluded.definition_ru, definition_ro = excluded.definition_ro, topics = excluded.topics;",
    );
  }
  parts.push("commit;", "");
  return parts.join("\n");
}
