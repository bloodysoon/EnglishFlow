import { DICTIONARY_LANGUAGES } from "./kaikki.ts";
import type { WordSetDefinition, WordsFile } from "./word-set.ts";

// Builds an idempotent SQL script for one word set: run it in the
// Supabase SQL editor (it bypasses RLS). Re-running updates in place, but
// never undoes work done in the admin panel: the publish switch is only
// set when the set is first created, and translations already marked
// reviewed are left alone.

// Standard SQL string literal; Supabase has standard_conforming_strings
// on, so only single quotes need escaping.
export function sqlString(value: string | null | undefined): string {
  if (value === null || value === undefined) return "null";
  return `'${value.replace(/'/g, "''")}'`;
}

function sqlTextArray(values: string[]): string {
  return values.length === 0 ? "'{}'::text[]" : `array[${values.map(sqlString).join(", ")}]::text[]`;
}

function sqlJson(value: unknown): string {
  return value === undefined || value === null ? "null" : `${sqlString(JSON.stringify(value))}::jsonb`;
}

export type SeedResult = {
  sql: string;
  // Words or translations left out, for the person running the import.
  warnings: string[];
};

export function buildSeedSql(definition: WordSetDefinition, words: WordsFile): SeedResult {
  const warnings: string[] = [];
  const wordRows: string[] = [];
  const translationRows: string[] = [];
  const itemRows: string[] = [];

  words.forEach((w, position) => {
    wordRows.push(
      `  (${[
        sqlString(w.lemma),
        sqlString(w.pos),
        sqlString(w.ipa),
        sqlString(w.definition),
        sqlString(w.example),
        sqlString(w.source),
        sqlString(w.level),
        sqlString(w.level ? w.levelSource : null),
      ].join(", ")})`,
    );
    if (!w.level) warnings.push(`${w.lemma}: no CEFR level (XP counts it as A1)`);
    itemRows.push(`  (${sqlString(w.lemma)}, ${sqlString(w.pos)}, ${position})`);

    for (const language of DICTIONARY_LANGUAGES) {
      const t = w.translations[language];
      if (!t) {
        warnings.push(`${w.lemma}: no ${language.toUpperCase()} translation, fill it in before publishing`);
        continue;
      }
      if (!t.reviewed) warnings.push(`${w.lemma}: ${language.toUpperCase()} translation not reviewed (hidden until it is)`);
      translationRows.push(
        `  (${[
          sqlString(w.lemma),
          sqlString(w.pos),
          sqlString(language),
          sqlString(t.translation),
          sqlTextArray(t.alternatives),
          sqlString(t.example ?? null),
          sqlString(t.source),
          t.reviewed ? "true" : "false",
        ].join(", ")})`,
      );
    }
  });

  const slug = sqlString(definition.slug);
  const parts = [
    `-- Word set "${definition.slug}": generated by scripts/word-sets.ts, do not edit by hand.`,
    `-- Content from Wiktionary (kaikki.org), CC BY-SA 4.0. Levels from the CEFR-J`,
    `-- Wordlist (Tono Laboratory, TUFS) and Octanove C1/C2 (CC BY-SA 4.0).`,
    "begin;",
    "",
    `insert into public.word_sets (slug, title, description, level, is_published)`,
    `values (${slug}, ${sqlJson(definition.title)}, ${sqlJson(definition.description)}, ${sqlString(definition.level ?? null)}, ${definition.published ? "true" : "false"})`,
    `on conflict (slug) do update set title = excluded.title, description = excluded.description, level = excluded.level;`,
  ];

  if (wordRows.length > 0) {
    parts.push(
      "",
      `insert into public.words (lemma, part_of_speech, ipa, definition, example, source, cefr_level, level_source)`,
      `values`,
      wordRows.join(",\n"),
      `on conflict (lemma, part_of_speech, owner_id) do update set ipa = excluded.ipa, definition = excluded.definition, example = excluded.example, source = excluded.source, cefr_level = excluded.cefr_level, level_source = excluded.level_source;`,
    );
  }

  if (translationRows.length > 0) {
    parts.push(
      "",
      `insert into public.word_translations (word_id, language, translation, alternatives, example, source, reviewed)`,
      `select w.id, v.language, v.translation, v.alternatives, v.example, v.source, v.reviewed`,
      `from (values`,
      translationRows.join(",\n"),
      `) as v (lemma, pos, language, translation, alternatives, example, source, reviewed)`,
      `join public.words w on w.lemma = v.lemma and w.part_of_speech = v.pos and w.owner_id is null`,
      `on conflict (word_id, language) do update set translation = excluded.translation, alternatives = excluded.alternatives, example = excluded.example, source = excluded.source, reviewed = excluded.reviewed`,
      `where not public.word_translations.reviewed;`,
    );
  }

  // Replace the set's word list so removed words leave the set.
  parts.push(
    "",
    `delete from public.word_set_items where set_id = (select id from public.word_sets where slug = ${slug});`,
  );

  if (itemRows.length > 0) {
    parts.push(
      "",
      `insert into public.word_set_items (set_id, word_id, position)`,
      `select s.id, w.id, v.position`,
      `from (values`,
      itemRows.join(",\n"),
      `) as v (lemma, pos, position)`,
      `join public.words w on w.lemma = v.lemma and w.part_of_speech = v.pos and w.owner_id is null`,
      `join public.word_sets s on s.slug = ${slug};`,
    );
  }

  parts.push("", "commit;", "");

  return { sql: parts.join("\n"), warnings };
}
